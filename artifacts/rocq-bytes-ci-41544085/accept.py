"""Bind an actual CI kernel checkpoint to official ZIP bytes and named Git inputs.

Offline acceptance rechecks structure/integrity; it does not rerun the kernel.
"""
from pathlib import Path
import gzip
import hashlib
import io
import json
import subprocess
import sys
import zipfile
ROOT=Path(__file__).resolve().parents[2]
HERE=Path(__file__).resolve().parent
sha=lambda p:hashlib.sha256(Path(p).read_bytes()).hexdigest()
read=lambda p:json.loads(Path(p).read_text())
SOURCE='415440853a0a18fb3dbc8855a2b23ea3eaa12f06'
MERGE='9a4187324f0da1ff5371ad80a10c7f95d7dc449d'
ZIP='18dd1fa4e17223327c78a68f8956f5ffa2950b2046bbbbdb71ef9fccf688f49e'
p=read(HERE/'provenance.json');a=p['artifact'];out=HERE/'download'
assert p['run']==41199833714 and p['job']==124533279559 and p['conclusion']=='success'
assert p['source_head']==SOURCE and p['merge_snapshot']==MERGE
assert a['id']==13041509676 and a['digest']=='sha256:'+ZIP and a['size_in_bytes']==210777
assert a['workflow_run']['id']==p['run'] and a['workflow_run']['head_sha']==SOURCE
assert a['workflow_run']['head_branch']=='codex/tcp-regression-495'
assert a['name']=='rocq-generated-bytes-'+MERGE and sha(HERE/'workflow-artifact.zip')==ZIP
with zipfile.ZipFile(HERE/'workflow-artifact.zip') as z:
 seen=set()
 for info in z.infolist():
  name=info.filename;q=Path(name)
  assert name not in seen and not q.is_absolute() and '..'not in q.parts and '\\'not in name
  seen.add(name)
  assert (info.external_attr>>16)&0o170000 != 0o120000
  if not info.is_dir():assert z.read(info)==(out/q).read_bytes(),name
subprocess.run([sys.executable,str(ROOT/'formal/rocq-bytes/verify.py'),'--out',str(out)],check=True)
r=read(out/'result.json');neg=read(HERE/'negative-controls.json');binding=read(HERE/'source-bindings.json')
assert r['status']=='kernel_checked_generated_bytes_ir_execution'
assert r['binding']['actions']==4 and r['binding']['invariants']==1
assert r['binding']['variables']==['buffer','whole','prefix','suffix','restored']
assert r['binding']['fields']==['data','offset']
inputs=r['input_hashes'];assert binding==dict(source_head=SOURCE,status='all_named_git_blobs_match',inputs=inputs)
assert len(inputs)==12
batch=('\n'.join(SOURCE+':'+n for n in inputs)+'\n').encode()
stream=io.BytesIO(subprocess.check_output(['git','cat-file','--batch'],input=batch,cwd=ROOT))
for n,h in inputs.items():
 header=stream.readline().decode().split();assert len(header)==3 and header[1]=='blob'
 raw=stream.read(int(header[2]));assert stream.read(1)==b'\n' and hashlib.sha256(raw).hexdigest()==h,n
assert not stream.read()
kernel=(out/'independent-kernel.log').read_text()
assert 'Modules were successfully checked'in kernel
for name in ('checked_generated_initial','checked_generated_step'):assert name in kernel
for name in ('wrong-count','wrong-order'):
 text=(out/(name+'-Proofs.log')).read_text()
 assert 'File "./Proofs.v"'in text and 'Error: Not convertible.'in text
assert neg['status']=='six_offline_binding_faults_rejected' and neg['original_evidence_unchanged']
assert not neg['new_kernel_execution'] and neg['source_report_sha256']==sha(out/'result.json')
assert neg['checker_sha256']==sha(ROOT/'formal/rocq-bytes/verify.py')
assert {x['fault']for x in neg['tests']}=={'object','lookup','narrowed-domain','statement','negative-source','scope'}
for row in neg['tests']:assert sha(HERE/row['log'])==row['log_sha256']
log=read(HERE/'job-log-hashes.json')
assert log['gzip_sha256']==sha(HERE/'job.log.gz')
assert hashlib.sha256(gzip.decompress((HERE/'job.log.gz').read_bytes())).hexdigest()==log['decoded_sha256']
result=dict(status='retained_kernel_checked_generated_byte_execution_accepted',source_head=SOURCE,
 merge_snapshot=MERGE,ci_run=p['run'],job=p['job'],artifact_id=a['id'],original_ci_zip_sha256=ZIP,
 source_model_sha256=r['binding']['source_sha256'],model_semantic_sha256=r['binding']['model_semantic_sha256'],
 source_ordered_assignments=4,generated_content_equalities=1,source_git_blobs_checked=len(inputs),
 original_ci_kernel_checked=True,empty_axiom_audits=2,local_kernel_recheck=False,new_kernel_execution=False,
 source_binding_is_kernel_proof=False,python_interpreter_proved=False,z3_translator_proved=False,
 tcp_protocol_proved=False,output_order_time_liveness_proved=False,linux_tcp_execution=False,full_protocol_complete=False,
 statements=['generated initial state satisfies generated full-byte equality',
 'for every byte-list environment/input and unbounded integer offset, executing generated ordered assignments preserves full concatenated content'],
 proof_hashes={n:sha(out/n)for n in ['Semantics.v','Compiled.v','Proofs.v','Semantics.vo','Compiled.vo','Proofs.vo']},
 source_fault_controls=r['negative_controls'],negative_controls_sha256=sha(HERE/'negative-controls.json'),
 trusted_components=r['trusted_components']+['GitHub runner/job/artifact provenance and official original ZIP'],
 scope='restricted generated byte IR execution, not TCP or a universal interpreter/compiler proof')
(HERE/'acceptance.json').write_text(json.dumps(result,indent=2)+'\n')
print('Accepted actual generated byte IR execution kernel checkpoint; no local kernel rerun')
