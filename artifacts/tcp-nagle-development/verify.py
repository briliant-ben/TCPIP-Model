"""Independently replay and regenerate the retained finite Nagle observation."""
import importlib.util
import json
from pathlib import Path
import subprocess
import sys
ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from protocol_lab.flow import read, write, digest
from protocol_lab.ir import load, require
from protocol_lab.profiles import control_packets
from protocol_lab.capture import normalize
from protocol_lab.packets import compare
from protocol_lab.symbolic import model_hash
from tools.replay_schedule import replay_inputs
HERE = Path(__file__).resolve().parent
result = read(HERE / 'result.json')
require(result['status'] == 'finite_basic_nagle_full_wire_timed_service_witness', 'Unsupported witness claim')
require(not result['new_C_execution'] and not result['linux_execution'] and not result['universal_refinement'], 'Evidence scope changed')
for name, sha in result['input_hashes'].items(): require(digest(ROOT / name) == sha, 'Input changed: ' + name)
for name, sha in result['file_hashes'].items(): require(digest(HERE / name) == sha, 'Artifact changed: ' + name)
model = load(ROOT / 'model/tcp-nagle.json')
require(model_hash(model) == result['model_semantic_sha256'], 'Model changed')
source = read(ROOT / 'ports/lwip-service/scenarios/duplicate-future-no-credit.json')
machine, audit, canonical = replay_inputs(model, source, read(HERE / 'witness.json'))
for name, value in [('trace', machine.trace), ('audit', audit), ('canonical', canonical)]:
    require(value == read(HERE / (name + '.json')), 'Replayed artifact differs: ' + name)
require(canonical['status'] == 'match', 'Canonical contract failed')
expected = control_packets(machine, source)
require(expected == read(HERE / 'expected.json'), 'Expected wire differs')
original = ROOT / 'artifacts/lwip-service/duplicate-future-no-credit'
actual, metadata = normalize(original / 'capture.pcap', read(ROOT / 'packet-profile.json'), expected,
    origin='external_capture', checksum_policy='strict', projection='tcp-connection-v1')
require(actual == read(HERE / 'observed.json') and metadata == read(HERE / 'metadata.json'), 'Capture mapping differs')
wire = compare(expected, actual, tolerance_ms=0, projection='tcp-connection-v1')
require(wire == read(HERE / 'difference.json') and wire['status'] == 'match', 'Strict wire difference changed')
callbacks = [{'time_ms': row['time_ms'], 'bytes': row['after']['variables']['cb_step_bytes']}
             for row in machine.trace if row['after']['variables']['cb_step_bytes']]
require(callbacks == result['callbacks'] == read(original / 'report.json')['summary']['sent_events'], 'Timed callbacks differ')
require(digest(original / 'difference.json') == result['original_wire_difference_sha256']
    and digest(original / 'receiver-difference.json') == result['original_service_difference_sha256'], 'Original Difference changed')
out = HERE / 'verification'; out.mkdir(exist_ok=True)
command = [sys.executable, str(ROOT / 'artifacts/tcp-sent-ledger-development/trace_worker.py'),
    '--model', str(ROOT / 'model/tcp-nagle.json'), '--trace', str(HERE / 'trace.json'),
    '--out', str(out), '--model-hash', model_hash(model)]
fresh = subprocess.run(command, capture_output=True, text=True, timeout=180)
(out / 'worker.log').write_text(fresh.stdout + fresh.stderr)
require(fresh.returncode == 0, 'Regenerated byte query failed')
spec = importlib.util.spec_from_file_location('stream_query_verifier', ROOT / 'ports/lwip-stream/run.py')
stream = importlib.util.module_from_spec(spec); spec.loader.exec_module(stream)
equivalence = stream.query_equivalence(HERE / 'symbolic/path.smt2', out / 'path.smt2')
write(out / 'equivalence.json', equivalence)
require(equivalence['status'] == 'unsat', 'Export equivalence not established')
program = 'import sys,z3;s=z3.Solver();s.set(timeout=10000);s.add(z3.parse_smt2_file(sys.argv[1]));print(s.check())'
exported = subprocess.run([sys.executable, '-c', program, str(HERE / 'symbolic/path.smt2')],
    capture_output=True, text=True, timeout=20)
(out / 'export.log').write_text(exported.stdout + exported.stderr)
require(exported.returncode == 0 and exported.stdout.strip() == 'sat', 'Original export not SAT')
for name, sha in result['input_hashes'].items(): require(digest(ROOT / name) == sha, 'Input changed while checking')
write(HERE / 'verification.json', dict(status='valid_finite_basic_nagle_observation',
    result_sha256=digest(HERE / 'result.json'), checker_sha256=digest(HERE / 'verify.py'),
    query_equivalence=equivalence, exported_query='sat',
    file_hashes={str(p.relative_to(HERE)): digest(p) for p in sorted(out.rglob('*')) if p.is_file()},
    new_C_execution=False, linux_execution=False, universal_refinement=False))
print('valid_finite_basic_nagle_observation')
